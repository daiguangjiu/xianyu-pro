START_B = 104          # 起始符 B：大小写字母、数字、常用符号都能装
STOP = 106             # 停止符
CHECK_MOD = 103        # 校验位取模


def values_of(text: str) -> list[int]:
    """文本 → 符号值序列（起始符 + 逐字符 + 校验位 + 停止符）；装不下的字符按空格算。"""
    values = [START_B]
    for ch in str(text or ""):
        code = ord(ch)
        values.append(code - 32 if 32 <= code <= 127 else 0)
    checksum = (values[0] + sum((i + 1) * v for i, v in enumerate(values[1:]))) % CHECK_MOD
    values.append(checksum)
    values.append(STOP)
    return values


def encode(text: str) -> str:
    """文本 → 位串（1 = 条，0 = 空）。"""
    return "".join(PATTERNS[v] for v in values_of(text))


def modules(text: str) -> int:
    """这条码一共占多少模块宽（换算实际宽度用）。"""
    return len(encode(text))
