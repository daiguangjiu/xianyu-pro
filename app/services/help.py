TOPIC_ORDER = ("push", "refund", "orders")


def topic(name: str) -> dict | None:
    """取一个模块的说明（名字不对返回 None）。"""
    return TOPICS.get(name)


def all_topics() -> list[dict]:
    """说明页侧边栏用：按固定顺序给出所有模块。"""
    return [{"key": k, "title": TOPICS[k]["title"]} for k in TOPIC_ORDER if k in TOPICS]
